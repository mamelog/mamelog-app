/// App spacing constants (multiples of 4).
abstract class AppSpacing {
  /// 0 spacing
  static const double none = 0;

  /// 4px spacing
  static const double xSmall = 4;
  static const double xs = xSmall;

  /// 8px spacing
  static const double small = 8;
  static const double sm = small;

  /// 12px spacing
  static const double mediumSmall = 12;
  static const double ms = mediumSmall;

  /// 16px spacing
  static const double medium = 16;
  static const double md = medium;

  /// 24px spacing
  static const double mediumLarge = 24;
  static const double ml = mediumLarge;

  /// 32px spacing
  static const double large = 32;
  static const double lg = large;

  /// 48px spacing
  static const double xLarge = 48;
  static const double xl = xLarge;

  /// 64px spacing
  static const double xxLarge = 64;
  static const double xxl = xxLarge;
}
